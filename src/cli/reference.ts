function generatedNote(version: string, what: string): string {
  return `Generated by \`pnpm generate:reference\` from the operation registry (OpenOutbound ${version}). Do not edit by hand; ${what}`;
}

function byId<T extends { id: string }>(a: T, b: T): number {
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

function cell(text: string | undefined): string {
  return (text ?? "").replace(/\s+/g, " ").replaceAll("|", "\\|").trim();
}

function typeLabel(field: FieldInfo): string {
  if (field.enum) return field.enum.map((value) => `\`${value}\``).join(" \\| ");
  if (field.kind === "array") return `${field.itemKind ?? "any"}[]`;
  if (field.kind === "any") return "json";
  return field.kind;
}

/** docs/reference/mcp-tools.md */
export function renderMcpToolsReference(catalog: Catalog): string {
  const lines = [
    "# MCP tools",
    "",
    generatedNote(catalog.version, "edit the tool and operation definitions instead."),
    "",
    "Select toolsets with `openoutbound mcp --toolsets core,leads` (or `OPENOUTBOUND_MCP_TOOLSETS`, or `/mcp?toolsets=` over HTTP). `all` selects every toolset. Composite tools take an `action` plus the fields of that action. Every call also accepts `workspace`, `reason` and `idempotency_key` (not repeated below); read actions accept `response_format` and spend or send actions accept `dry_run`.",
    "",
  ];
  const operations = new Map(catalog.operations.map((op) => [op.id, op]));
  for (const toolset of TOOLSETS) {
    const { specs } = buildToolSpecs(catalog, new Set([toolset]));
    const tools = [...specs].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    lines.push(`## Toolset \`${toolset}\``, "", TOOLSET_NOTES[toolset] ?? "", "");
    if (tools.length === 0) {
      lines.push("No tools in this build.", "");
      continue;
    }
    for (const tool of tools) lines.push(...renderTool(tool, operations));
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function renderTool(tool: McpToolSpec, operations: Map<string, OperationInfo>): string[] {
  const hints = tool.annotations;
  const flags = [
    hints.readOnlyHint ? "read-only" : null,
    hints.destructiveHint ? "destructive" : null,
    hints.idempotentHint ? "idempotent" : null,
    hints.openWorldHint ? "open world" : null,
  ].filter(Boolean);
  const lines = [`### \`${tool.name}\`: ${tool.title}`, "", tool.description.trim(), ""];
  lines.push(`Annotations: ${flags.length > 0 ? flags.join(", ") : "none"}.`, "");
  if (tool.actions) {
    lines.push("| Action | Operation | Effect | Summary |", "| --- | --- | --- | --- |");
    for (const [action, operation] of Object.entries(tool.actions)) {
      const known = operations.get(operation.id) ?? operation;
      lines.push(`| \`${action}\` | \`${known.id}\` | ${known.effect} | ${cell(known.summary)} |`);
    }
  } else if (tool.operation) {
    const known = operations.get(tool.operation.id) ?? tool.operation;
    lines.push(`Operation: \`${known.id}\` (${known.effect}): ${cell(known.summary)}.`);
  }
  const fields = fieldsOf(tool.inputSchema).filter(
    (field) => field.name !== "action" && !ALWAYS_ACCEPTED.has(field.name),
  );
  if (fields.length > 0) {
    lines.push("", "| Field | Type | Required | Description |", "| --- | --- | --- | --- |");
    for (const field of fields) {
      lines.push(
        `| \`${field.name}\` | ${typeLabel(field)} | ${field.required ? "yes" : "no"} | ${cell(field.description)} |`,
      );
    }
  }
  lines.push("");
  return lines;
}

