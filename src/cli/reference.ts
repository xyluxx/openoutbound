/** docs/reference/cli.md */
export function renderCliReference(catalog: Catalog): string {
  const lines = [
    "# CLI",
    "",
    generatedNote(catalog.version, "edit the operation definitions instead."),
    "",
    "## Global options",
    "",
    'Global options go before the command: `openoutbound --url http://127.0.0.1:7331 leads search --query "vp operations"`. Operation commands also accept them after the command, and every command accepts `--home` after it.',
    "",
    "| Option | Description |",
    "| --- | --- |",
    "| `--home <dir>` | Engine home with `.env` and `.openoutbound/` (env `OPENOUTBOUND_HOME`). Default: the current directory when it has them, else the package folder when it has them, else the current directory. |",
    "| `--workspace <id\\|slug>` | Workspace for operation commands (env `OPENOUTBOUND_WORKSPACE`). |",
    "| `--url <url>` | Call a running server instead of opening the database (bridge mode, env `OPENOUTBOUND_URL`). |",
    "| `--api-key <key>` | API key for bridge mode (env `OPENOUTBOUND_API_KEY`). |",
    "| `--json` | Print raw JSON on stdout. |",
    "| `--dry-run` / `--no-dry-run` | Preview only, or apply operations that preview by default. |",
    "| `--reason <text>` | Why, in one sentence (audit log). |",
    "| `--idempotency-key <key>` | Makes retries safe. |",
    "",
    "Operation commands take `--input <json|@file.json>` for the whole input (flags override its fields). Arrays accept repeated flags or comma lists, objects accept JSON or `@file.json`, booleans are `--flag` / `--no-flag`. Data goes to stdout, messages and hints to stderr. Exit codes: 0 ok, 1 error (also a mailbox login test that failed in `mailboxes test` or `mailboxes add --test`, after printing the result), 2 validation or usage error.",
    "",
    "## Built-in commands",
    "",
    "| Command | Description |",
    "| --- | --- |",
    ...BUILTINS.map(
      ([command, description]) => `| \`openoutbound ${cell(command)}\` | ${cell(description)} |`,
    ),
    "",
    "## Operation commands",
    "",
  ];
  const groups = new Map<string, OperationInfo[]>();
  for (const operation of [...catalog.operations].sort(byId)) {
    const group = operation.cli[0] ?? operation.id;
    groups.set(group, [...(groups.get(group) ?? []), operation]);
  }
  for (const group of [...groups.keys()].sort()) {
    lines.push(`### ${group}`, "");
    for (const operation of groups.get(group) ?? []) {
      lines.push(`#### \`openoutbound ${operation.cli.join(" ")}\``, "");
      lines.push(
        `${operation.summary}. Effect: ${operation.effect}. Operation: \`${operation.id}\`.`,
        "",
      );
      lines.push(operation.description.trim(), "");
      const fields = fieldsOf(operation.input_schema).filter(
        (field) =>
          field.name === "response_format" ||
          !(RESERVED_INPUT_FIELDS as readonly string[]).includes(field.name),
      );
      if (fields.length > 0) {
        lines.push("| Flag | Type | Required | Description |", "| --- | --- | --- | --- |");
        for (const field of fields) {
          const flag =
            field.kind === "boolean"
              ? `--${flagName(field.name)}` + ` / --no-${flagName(field.name)}`
              : `--${flagName(field.name)}`;
          lines.push(
            `| \`${flag}\` | ${typeLabel(field)} | ${field.required ? "yes" : "no"} | ${cell(field.description)} |`,
          );
        }
        lines.push("");
      }
      const example = operation.examples[0];
      if (example) {
        // A field named input takes the --input flag, so such examples use one flag per field.
        const usage = fields.some((field) => field.name === "input")
          ? exampleLine(operation)
          : `--input '${JSON.stringify(example.input)}'`;
        lines.push(`Example (${example.title}): \`${usage}\``, "");
      }
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** docs/reference/rest-api.md */
export function renderRestReference(catalog: Catalog): string {
  const lines = [
    "# REST API",
    "",
    generatedNote(catalog.version, "the full schema is in [openapi.json](./openapi.json)."),
    "",
    "## Basics",
    "",
    "- Base URL: `OPENOUTBOUND_BASE_URL` (default `http://localhost:7331`). Start the server with `openoutbound serve`.",
    "- Auth: `Authorization: Bearer oo_...` on `/v1/*` and `/mcp`. Create keys with `openoutbound keys create`.",
    "- Workspace: from a workspace key, or the `OpenOutbound-Workspace` header (id or slug) with instance keys. `OpenOutbound-Bind-Workspace` binds the key to one workspace for the request: other workspaces and instance-level operations answer 403 `forbidden`.",
    "- Idempotency: `Idempotency-Key` header (or `idempotency_key` in the body). Same key and body return the first result for 24 hours; a different body returns 409 `idempotency_mismatch`.",
    "- Errors: RFC 9457 `application/problem+json` with `code`, `detail`, `hint` and `details` (field issues). Validation errors are 422, bodies that are not JSON are 400.",
    "- Rate limit: 600 requests per minute per key by default (429 with `Retry-After`). Request ids: `X-Request-Id` (sent or generated). Body limit: 10 MB.",
    '- Results: work that waits for a human returns 202 with `{ status: "awaiting_approval", approval_id, summary }`; background work returns 202 with `{ job_id, status }`; dry runs return `{ dry_run: true, preview, warnings }`.',
    "",
    "## Generic routes",
    "",
    "| Method | Path | Description |",
    "| --- | --- | --- |",
    "| GET | `/health` | Health check (no auth). |",
    "| GET | `/openapi.json` | OpenAPI 3.1 document (no auth). |",
    "| GET | `/v1/ops` | Registry listing: operations with input JSON Schemas, and MCP tools. |",
    "| POST | `/v1/ops/{operation_id}` | Run any operation: the JSON body is its input. |",
    "| GET, POST, DELETE | `/mcp` | MCP over Streamable HTTP (stateless). `?toolsets=core,leads` selects toolsets. |",
    "",
    "## Operations",
    "",
  ];
  const groups = new Map<string, OperationInfo[]>();
  for (const operation of [...catalog.operations].sort(byId)) {
    const group = operation.id.split(".")[0] as string;
    groups.set(group, [...(groups.get(group) ?? []), operation]);
  }
  for (const group of [...groups.keys()].sort()) {
    lines.push(
      `### ${group}`,
      "",
      "| Method | Path | Operation | Effect | Scopes | Summary |",
      "| --- | --- | --- | --- | --- | --- |",
    );
    for (const operation of groups.get(group) ?? []) {
      const method = operation.http?.method ?? "POST";
      const path = operation.http?.path ?? `/v1/ops/${operation.id}`;
      lines.push(
        `| ${method} | \`${path}\` | \`${operation.id}\` | ${operation.effect} | ${operation.scopes.join(", ")} | ${cell(operation.summary)} |`,
      );
    }
    lines.push("");
  }
  if (groups.size === 0) lines.push("No operations in this build.", "");
  lines.push(
    "Every operation is also reachable as `POST /v1/ops/{operation_id}`. Path parameters (`:name`) and query parameters map to input fields of the same name; query values are converted to the field type (numbers, booleans, repeated or comma-separated arrays, JSON objects).",
    "",
  );
  return `${lines.join("\n").trimEnd()}\n`;
}

/** Every reference file, keyed by path relative to docs/reference/. */
export function renderReference(registry: Registry, version: string): Record<string, string> {
  const catalog = buildCatalog(registry, version);
  const openapi = buildOpenApi(registry, { serverUrl: "http://localhost:7331", version });
  return {
    "mcp-tools.md": renderMcpToolsReference(catalog),
    "cli.md": renderCliReference(catalog),
    "rest-api.md": renderRestReference(catalog),
    "openapi.json": `${JSON.stringify(openapi, null, 2)}\n`,
  };
}
